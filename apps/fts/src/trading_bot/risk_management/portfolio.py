# src/trading_bot/risk_management/portfolio.py

import logging
from typing import Dict, Optional

from quant_core.enums import Currency, OrderSide, OrderStatus

from ..core.schemas import (
    CashBalance,
    ExecutionResult,
    MarketData,
    OrderRequest,
)
from ..core.schemas import Portfolio as PortfolioSchema
from ..core.schemas import (
    Position,
)

logger = logging.getLogger(__name__)


class Portfolio:
    """
    Manages the in-memory state of the bot's positions and balances.

    Nothing here touches a database: fills are the truth and are saved by the
    execution engine; positions are derived from them (D19).

    This class is agnostic to the specific exchange and operates
    purely on the abstract data contracts (schemas). It is responsible
    for tracking assets, calculating P&L, and providing a snapshot
    of the current portfolio state.
    """

    def __init__(
        self,
        initial_balance: float,
        quote_currency: str | Currency = Currency.USD,
    ) -> None:
        """
        Initializes the portfolio with a starting balance.

        :param initial_balance: The total starting capital in the quote currency.
        :param quote_currency: The accounting currency, one of quant_core's
            ``Currency`` values (e.g. "USD"); anything else raises ValueError.
        """
        self.initial_balance: float = initial_balance
        self._cash_balance: float = initial_balance
        self.quote_currency: str = Currency(quote_currency).value

        # In-memory state
        # Key: f"{instrument_id}:{outcome}" if outcome else instrument_id
        self._positions: Dict[str, Position] = {}
        # Key: order_id -> OrderRequest schema
        self._open_orders: Dict[str, OrderRequest] = {}
        # Last bar close seen per instrument_id, carried over ticks without a bar
        self._last_close: Dict[str, float] = {}

        logger.info(
            f"Portfolio initialized with cash: {initial_balance:.2f} "
            f"{self.quote_currency}"
        )

    def add_open_order(self, order_id: str, order: OrderRequest) -> None:
        """
        Adds an order to the in-memory list of open orders.
        This is used to calculate available balance.

        :param order_id: The unique order ID generated by the execution engine.
        :param order: The OrderRequest schema object.
        """
        if order_id in self._open_orders:
            logger.warning(f"Order {order_id} already tracked.")
            return
        self._open_orders[order_id] = order
        logger.debug(f"Added open order {order_id} to portfolio.")

    def fill_for(self, result: ExecutionResult) -> Optional[OrderRequest]:
        """The order ``update_order_status(result)`` would fill, without
        applying anything, so the fill can be saved before the Portfolio
        changes (fills are the truth)."""
        if result.status != OrderStatus.FILLED or not result.filled_quantity > 0:
            return None
        return self._open_orders.get(result.order_id)

    def update_order_status(self, result: ExecutionResult) -> Optional[OrderRequest]:
        """
        Updates the portfolio state based on an execution result.
        This is the primary method for processing fills, cancels, or failures.

        :param result: The ExecutionResult schema object from the engine.
        :return: The order whose fill was applied, or None when nothing was
                 filled (so the caller saves exactly the fills applied here).
        """
        # Remove order from tracking, whether filled or failed
        order = self._open_orders.pop(result.order_id, None)

        if result.status in (
            OrderStatus.CANCELLED,
            OrderStatus.REJECTED,
            OrderStatus.FAILED,
        ):
            logger.info(
                f"Order {result.order_id} finalized with status: {result.status}"
            )
            return None

        if result.status != OrderStatus.FILLED:
            if order:
                self._open_orders[result.order_id] = order  # Put it back
            logger.warning(
                f"Received non-final status {result.status} for {result.order_id}. "
                "Portfolio will not update until FILLED."
            )
            return None

        if order is None:
            logger.error(
                f"Received fill for untracked order {result.order_id}. "
                "State may be inconsistent."
            )
            return None

        if result.filled_quantity <= 0:
            logger.warning(f"Order {result.order_id} FILLED with no quantity.")
            return None

        # --- Process the Fill (Agnostic / Outcome-aware Logic) ---
        fill_cost = result.filled_quantity * result.avg_price
        key = (
            f"{order.instrument_id}:{order.outcome}"
            if order.outcome
            else order.instrument_id
        )
        pos = self._positions.get(key)
        realized_pnl = 0.0
        trade_size = result.filled_quantity
        trade_price = result.avg_price

        # Signed size: positive for BUY, negative for SELL
        trade_delta = trade_size if order.side == OrderSide.BUY else -trade_size

        # Adjust cash balance based on trade
        if order.side == OrderSide.BUY:
            self._cash_balance -= fill_cost
        else:  # SELL
            self._cash_balance += fill_cost

        if pos is None:  # Opening a new position
            pos = Position(
                instrument_id=order.instrument_id,
                outcome=order.outcome,
                quantity=trade_delta,
                cost_basis=trade_price,
            )
            self._positions[key] = pos

        else:  # Modifying an existing position
            old_size = pos.quantity
            new_size = old_size + trade_delta

            is_flipping = (old_size * new_size) < 0
            is_adding = abs(new_size) > abs(old_size)
            is_reducing = abs(new_size) < abs(old_size) and not is_flipping

            if is_adding:
                # Calculate new average entry price
                old_value = abs(old_size) * pos.cost_basis
                new_trade_value = trade_size * trade_price
                new_avg_price = (old_value + new_trade_value) / abs(new_size)
                pos.cost_basis = new_avg_price
                pos.quantity = new_size

            elif is_reducing:
                # Realize P&L, entry price remains the same
                if old_size > 0:  # Closing part of a long
                    realized_pnl = trade_size * (trade_price - pos.cost_basis)
                else:  # Closing part of a short
                    realized_pnl = trade_size * (pos.cost_basis - trade_price)
                pos.quantity = new_size

            elif is_flipping:
                # Realize P&L on the closed portion, set new entry price
                size_closed = abs(old_size)
                if old_size > 0:  # Flipping long to short
                    realized_pnl = size_closed * (trade_price - pos.cost_basis)
                else:  # Flipping short to long
                    realized_pnl = size_closed * (pos.cost_basis - trade_price)
                pos.quantity = new_size
                pos.cost_basis = trade_price  # New entry price is the flip price

            # Check if position was closed out
            if abs(new_size) < 1e-9:
                self._positions.pop(key)

        logger.info(
            f"Fill processed for order {result.order_id}. "
            f"Market: {key}, New Size: {pos.quantity if pos else 0:.4f}. "
            f"Realized P&L: {realized_pnl:.2f}. New cash: {self._cash_balance:.2f}"
        )
        return order

    # --- Valuation (PR 7b): one price rule for equity ------------------------

    def mark(self, market_data_map: Dict[str, MarketData]) -> None:
        """Remember the latest bar close of every instrument in the map. A tick
        without a bar keeps the previous close: a missing bar is not a price of 0."""
        for instrument_id, market_data in market_data_map.items():
            if market_data.recent_bars:
                self._last_close[instrument_id] = market_data.recent_bars[-1].close

    def last_close(self, instrument_id: str) -> Optional[float]:
        return self._last_close.get(instrument_id)

    def mark_price(self, pos: Position) -> float:
        """
        Last close of the position's instrument. Before any close is seen, and
        for prediction-market outcome positions (the bars are the instrument's,
        not the YES/NO side's; see docs/BACKLOG.md PR 7b), the cost basis.
        """
        close = None if pos.outcome else self._last_close.get(pos.instrument_id)
        return pos.cost_basis if close is None else close

    def equity(self, market_data_map: Dict[str, MarketData]) -> float:
        """Cash plus every position at its mark price. The single equity
        number: the backtest log, the risk limits and the sizers all use it."""
        self.mark(market_data_map)
        return self._cash_balance + sum(
            pos.quantity * self.mark_price(pos) for pos in self._positions.values()
        )

    def calculate_unrealized_pnl(
        self, market_data_map: Dict[str, MarketData]
    ) -> Dict[str, float]:
        """
        Unrealized P&L at the price a position could be closed at: the best bid
        (long) or ask (short). Used only to check a trade against the
        allocation limits; equity uses ``equity()``. Without a book, the mark
        price.

        :param market_data_map: A map of instrument_id to MarketData.
        :return: A dictionary mapping position keys to their unrealized P&L.
        """
        self.mark(market_data_map)
        pnl_map = {}
        for key, pos in self._positions.items():
            market_data = market_data_map.get(pos.instrument_id)
            current_price = self.mark_price(pos)

            if market_data:
                try:
                    # If long (size > 0), we'd sell (use best bid)
                    if (
                        pos.quantity > 0
                        and market_data.order_book
                        and market_data.order_book.bids
                    ):
                        current_price = market_data.order_book.bids[0].price
                    # If short (size < 0), we'd buy (use best ask)
                    elif (
                        pos.quantity < 0
                        and market_data.order_book
                        and market_data.order_book.asks
                    ):
                        current_price = market_data.order_book.asks[0].price
                except IndexError:
                    pass  # No liquidity, use the mark price

            unrealized_pnl = pos.quantity * (current_price - pos.cost_basis)
            pnl_map[key] = unrealized_pnl

        return pnl_map

    def get_state(self, market_data_map: Dict[str, MarketData]) -> PortfolioSchema:
        """
        Generates a snapshot of the current portfolio state.

        :param market_data_map: A dictionary mapping instrument_id to its
                                latest MarketData, used for pricing.
        :return: A Portfolio schema object.
        """
        # 1. Calculate cash committed to open BUY orders
        committed_cash = 0.0
        open_orders_list = list(self._open_orders.values())
        for order in open_orders_list:
            if order.side == OrderSide.BUY:
                committed_cash += order.quantity * order.price

        available_balance = self._cash_balance - committed_cash

        # 2. Total balance = the single marked equity (PR 7b)
        positions_list = list(self._positions.values())
        total_balance = self.equity(market_data_map)

        return PortfolioSchema(
            cash_balances=[
                CashBalance(
                    currency=self.quote_currency,
                    total=total_balance,
                    available=available_balance,
                )
            ],
            positions=positions_list,
            open_orders=open_orders_list,
        )

    @property
    def cash_balance(self) -> float:
        """Returns the current cash balance in quote currency."""
        return self._cash_balance

    @property
    def positions(self) -> Dict[str, Position]:
        """Returns the dictionary of current open positions."""
        return self._positions

    @property
    def open_orders(self) -> Dict[str, OrderRequest]:
        """Returns the dictionary of currently tracked open orders."""
        return self._open_orders
