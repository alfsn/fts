# src/trading_bot/runs/tables.py
"""
The tables that make up a run (M1). Hidden: only ``trading_bot.runs`` imports
this module (import-linter contract). Everyone else uses ``RunRecorder`` to
write and ``RunStore`` to read or delete.
"""

from datetime import datetime
from typing import List, Optional

from quant_data.db.models import Market
from sqlalchemy import (
    DateTime,
    Enum,
    ForeignKey,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from ..core.database import Base
from ..core.enums import OrderSide, OrderStatus

Market.orders = relationship("OrderLog", back_populates="market")
Market.trades = relationship("TradeLog", back_populates="market")


class RunLog(Base):
    """The run card: one row per run."""

    __tablename__ = "runs"

    run_id: Mapped[str] = mapped_column(String, primary_key=True)
    kind: Mapped[str] = mapped_column(String, index=True, nullable=False)
    strategy_name: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    instrument_id: Mapped[Optional[str]] = mapped_column(
        String, index=True, nullable=True
    )
    initial_cash: Mapped[Optional[float]] = mapped_column(nullable=True)
    start_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    end_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )


class RunSegmentLog(Base):
    """Which model traded a run, from when to when (one row per backtest
    today; one per walk-forward fold in R2)."""

    __tablename__ = "run_segments"

    id: Mapped[int] = mapped_column(primary_key=True)
    run_id: Mapped[str] = mapped_column(String, index=True, nullable=False)
    model_id: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    start_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    end_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )


class OrderLog(Base):
    """
    SQLAlchemy ORM Model for logging every order request and its state.

    This table tracks the full lifecycle of an order, combining data
    from the OrderRequest and ExecutionResult schemas.
    """

    __tablename__ = "order_logs"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    # This ID should be generated by our system or the exchange
    order_id: Mapped[str] = mapped_column(
        String, unique=True, index=True, nullable=False
    )
    run_id: Mapped[Optional[str]] = mapped_column(String, index=True)
    instrument_id: Mapped[str] = mapped_column(
        String, ForeignKey("markets.instrument_id"), index=True, nullable=False
    )
    # Store the strategy name for performance attribution
    strategy_name: Mapped[Optional[str]] = mapped_column(String, index=True)

    # --- Data from OrderRequest ---
    side: Mapped[OrderSide] = mapped_column(Enum(OrderSide), nullable=False)
    outcome: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    requested_quantity: Mapped[float] = mapped_column(nullable=False)
    requested_price: Mapped[float] = mapped_column(nullable=False)

    # --- Data from ExecutionResult ---
    status: Mapped[OrderStatus] = mapped_column(
        Enum(OrderStatus), nullable=False, index=True
    )
    filled_quantity: Mapped[float] = mapped_column(default=0.0)
    avg_fill_price: Mapped[float] = mapped_column(default=0.0)

    # Timestamps for tracking the order's lifecycle
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), onupdate=func.now()
    )

    # Relationships
    market: Mapped["Market"] = relationship("Market", back_populates="orders")
    # One OrderLog can have many individual TradeLog entries (fills)
    trades: Mapped[List["TradeLog"]] = relationship("TradeLog", back_populates="order")

    def __repr__(self) -> str:
        return f"<OrderLog(order_id='{self.order_id}', status='{self.status}')>"


class TradeLog(Base):
    """
    SQLAlchemy ORM Model for logging individual fill events.

    This is a clean table of only executed trades, ideal for
    performance analysis and backtesting. Each entry represents
    a single fill (or partial fill).
    """

    __tablename__ = "trade_logs"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    run_id: Mapped[str] = mapped_column(String, index=True, nullable=False)
    # Link back to the order that generated this trade
    order_id: Mapped[Optional[str]] = mapped_column(
        String, ForeignKey("order_logs.order_id"), index=True
    )

    instrument_id: Mapped[str] = mapped_column(
        String, ForeignKey("markets.instrument_id"), index=True, nullable=False
    )
    side: Mapped[OrderSide] = mapped_column(Enum(OrderSide), nullable=False)
    outcome: Mapped[Optional[str]] = mapped_column(String, nullable=True)

    # The quantity and price of this specific fill
    quantity: Mapped[float] = mapped_column(nullable=False)
    fill_price: Mapped[float] = mapped_column(nullable=False)

    # The bar time of the fill (ExecutionResult.timestamp), never the wall clock
    fill_timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), index=True, nullable=False
    )

    # Relationships
    order: Mapped[Optional["OrderLog"]] = relationship(
        "OrderLog", back_populates="trades"
    )
    market: Mapped["Market"] = relationship("Market", back_populates="trades")

    def __repr__(self) -> str:
        return (
            f"<TradeLog(id={self.id}, order_id='{self.order_id}', "
            f"quantity={self.quantity} @ {self.fill_price})>"
        )


class PredictionLog(Base):
    """
    SQLAlchemy ORM Model for machine learning prediction logs.
    Maps all prediction logs to a single table.
    """

    __tablename__ = "prediction_logs"

    __table_args__ = (
        UniqueConstraint(
            "timestamp",
            "instrument_id",
            "strategy_name",
            "run_id",
            "log_type",
            name="uq_prediction_log",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    run_id: Mapped[str] = mapped_column(String, index=True, nullable=False)
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), index=True, nullable=False
    )
    strategy_name: Mapped[str] = mapped_column(String, index=True, nullable=False)

    # Store model outputs (probabilities or predicted values) as JSON string
    prediction_output: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Store final signal decision and confidence
    predicted_signal: Mapped[str] = mapped_column(String, nullable=False)
    confidence: Mapped[float] = mapped_column(nullable=False)

    # Optional actual outcome for visual analysis
    actual_future_return: Mapped[Optional[float]] = mapped_column(nullable=True)

    instrument_id: Mapped[str] = mapped_column(
        String, ForeignKey("markets.instrument_id"), index=True, nullable=False
    )
    market: Mapped["Market"] = relationship("Market")

    log_type: Mapped[str] = mapped_column(String, index=True, nullable=False)

    __mapper_args__ = {
        "polymorphic_on": "log_type",
        "polymorphic_identity": "base",
    }


class ModelPredictionLog(PredictionLog):
    """Logs predictions generated during live/paper trading."""

    __mapper_args__ = {
        "polymorphic_identity": "live",
    }

    def __repr__(self) -> str:
        return (
            f"<ModelPredictionLog(run_id='{self.run_id}', instrument_id='{self.instrument_id}', "
            f"strategy='{self.strategy_name}', signal='{self.predicted_signal}')>"
        )


class BacktestPredictionLog(PredictionLog):
    """Logs predictions generated during historical simulation backtests."""

    __mapper_args__ = {
        "polymorphic_identity": "backtest",
    }

    def __repr__(self) -> str:
        return (
            f"<BacktestPredictionLog(run_id='{self.run_id}', instrument_id='{self.instrument_id}', "
            f"strategy='{self.strategy_name}', signal='{self.predicted_signal}')>"
        )


class BacktestEquityLog(Base):
    """Logs cash, position quantity, and overall equity per tick for a backtest simulation run."""

    __tablename__ = "backtest_equity_logs"

    __table_args__ = (
        UniqueConstraint(
            "timestamp",
            "run_id",
            name="uq_backtest_equity_log",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    run_id: Mapped[str] = mapped_column(String, index=True, nullable=False)
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), index=True, nullable=False
    )
    cash: Mapped[float] = mapped_column(nullable=False)
    position: Mapped[float] = mapped_column(nullable=False)
    close: Mapped[float] = mapped_column(nullable=False)
    equity: Mapped[float] = mapped_column(nullable=False)

    def __repr__(self) -> str:
        return (
            f"<BacktestEquityLog(run_id='{self.run_id}', timestamp='{self.timestamp}', "
            f"equity={self.equity:.2f})>"
        )


# The one list of run tables: delete, reset and the coverage test use it.
# Parents come before children (trade_logs points at order_logs), so deleting
# in reverse never trips a foreign key.
_RUN_TABLE_SET = {
    RunLog.__table__,
    RunSegmentLog.__table__,
    OrderLog.__table__,
    TradeLog.__table__,
    PredictionLog.__table__,
    BacktestEquityLog.__table__,
}
RUN_TABLES = tuple(t for t in Base.metadata.sorted_tables if t in _RUN_TABLE_SET)
